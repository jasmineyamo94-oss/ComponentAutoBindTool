using System;
using System.Reflection;
using System.Text;
using ComponentAutoBindTool.ViewCore;
using UnityEngine;

namespace ComponentAutoBindTool.Editor
{
    internal static class AutoBindCodeGenerator
    {
        internal const string HostInterface = "global::ComponentAutoBindTool.ViewCore.IAutoBindHost";

        // 只构造源码；写入、保存和导入全部由流水线提交。
        public static string BuildCode(AutoBindBuildInput input)
        {
            Type type = input.HostType;
            MethodInfo ensure = FindBaseMethod(type, "EnsureAutoBind", typeof(GameObject));
            MethodInfo getter = FindBaseMethod(type, "GetGeneratedUIView");
            bool generateGetter = getter != null && getter.ReturnType == typeof(object);
            bool publicOverride = ensure != null && ensure.IsPublic;
            string indent = string.IsNullOrEmpty(type.Namespace) ? "" : "    ";
            var code = new StringBuilder(2048);
            void Line(string text = "") => code.Append(text).Append('\n');
            Line("// <auto-generated>");
            Line("// 此文件由 ComponentAutoBindTool 生成，请通过 Inspector 重新生成。");
            Line("// AutoBind host: " + type.FullName);
            Line("// </auto-generated>");
            if (indent.Length != 0)
            {
                Line("namespace " + EscapeQualifiedName(type.Namespace));
                Line("{");
            }
            Line(indent + (type.IsPublic ? "public" : "internal") + " partial class " + EscapeIdentifier(type.Name) +
                 " : " + HostInterface);
            Line(indent + "{");
            string member = indent + "    ";
            string body = member + "    ";
            Line(member + "[global::System.Serializable]");
            Line(member + "public class UIView : global::ComponentAutoBindTool.ViewCore.IUiViewComponent");
            Line(member + "{");
            foreach (var binding in input.Bindings)
            {
                Line(body + "public " + FormatTypeName(binding.BindCom.GetType()) + " " +
                     AutoBindFieldNameUtility.BuildFieldName(binding.Name) + ";");
            }
            Line(member + "}");
            Line();
            Line(member + "private UIView view;");
            Line();
            string modifier = ensure == null ? "public" : Access(ensure, type) + " override";
            Line(member + modifier + " void EnsureAutoBind(global::UnityEngine.GameObject go)");
            Line(member + "{");
            Line(body + "if (view != null) return;");
            Line(body + "if (go == null || !go.TryGetComponent<global::ComponentAutoBindTool.Core.ComponentAutoBindTool>(out var autoBindTool))");
            Line(body + "{");
            Line(body + "    global::UnityEngine.Debug.LogError(\"[" + type.Name + "] AutoBind 根节点或绑定组件不存在。\", go);");
            Line(body + "    return;");
            Line(body + "}");
            Line(body + "var boundView = new UIView");
            Line(body + "{");
            for (int i = 0; i < input.Bindings.Count; i++)
            {
                var binding = input.Bindings[i];
                string name = AutoBindFieldNameUtility.BuildFieldName(binding.Name);
                Line(body + "    " + name + " = autoBindTool.GetBindComponent<" + FormatTypeName(binding.BindCom.GetType()) +
                     ">(" + i + ", nameof(UIView." + name + ")),");
            }
            Line(body + "};");
            foreach (var binding in input.Bindings)
            {
                Line(body + "if (boundView." + AutoBindFieldNameUtility.BuildFieldName(binding.Name) + " == null) return;");
            }
            Line(body + "view = boundView;");
            Line(member + "}");
            if (ensure != null && !publicOverride)
            {
                Line(member + "void " + HostInterface + ".EnsureAutoBind(global::UnityEngine.GameObject go) => EnsureAutoBind(go);");
            }
            if (generateGetter)
            {
                Line();
                Line(member + Access(getter, type) + " override object GetGeneratedUIView()");
                Line(member + "{");
                Line(body + "if (view == null) EnsureAutoBind(gameObject);");
                Line(body + "return view;");
                Line(member + "}");
            }
            Line(indent + "}");
            if (indent.Length != 0) Line("}");
            return code.ToString();
        }

        internal static MethodInfo FindBaseMethod(Type target, string name, params Type[] parameters)
        {
            const BindingFlags flags = BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public |
                                       BindingFlags.NonPublic | BindingFlags.DeclaredOnly;
            for (Type current = target.BaseType; current != null; current = current.BaseType)
            {
                MethodInfo method = current.GetMethod(name, flags, null, parameters, null);
                // 最近声明决定可见性；不能跳过 sealed / new 隐藏去重写祖先。
                if (method != null) return method;
            }
            return null;
        }

        internal static bool CanOverride(MethodInfo method, Type returnType)
        {
            return method != null && method.ReturnType == returnType && !method.IsStatic &&
                !method.ContainsGenericParameters && method.IsVirtual && !method.IsFinal &&
                (method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly);
        }

        private static string Access(MethodInfo method, Type host)
        {
            if (method.IsPublic) return "public";
            return method.IsFamilyOrAssembly && method.DeclaringType.Assembly == host.Assembly
                ? "protected internal" : "protected";
        }

        internal static string EscapeIdentifier(string name) => "@" + name;

        private static string EscapeQualifiedName(string name) => string.Join(".", Array.ConvertAll(name.Split('.'), EscapeIdentifier));

        internal static string FormatTypeName(Type type)
        {
            if (type.IsArray) return FormatTypeName(type.GetElementType()) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
            Type[] arguments = type.IsGenericType ? type.GetGenericArguments() : Type.EmptyTypes;
            var chain = new System.Collections.Generic.Stack<Type>();
            for (Type current = type; current != null; current = current.DeclaringType) chain.Push(current);
            var result = new StringBuilder("global::");
            if (!string.IsNullOrEmpty(type.Namespace)) result.Append(EscapeQualifiedName(type.Namespace)).Append('.');
            int argumentIndex = 0;
            while (chain.Count != 0)
            {
                Type current = chain.Pop();
                string name = current.Name;
                int tick = name.IndexOf('`');
                result.Append(EscapeIdentifier(tick < 0 ? name : name.Substring(0, tick)));
                if (tick >= 0)
                {
                    int count = int.Parse(name.Substring(tick + 1));
                    result.Append('<');
                    for (int i = 0; i < count; i++)
                    {
                        if (i != 0) result.Append(", ");
                        result.Append(FormatTypeName(arguments[argumentIndex++]));
                    }
                    result.Append('>');
                }
                if (chain.Count != 0) result.Append('.');
            }
            return result.ToString();
        }
    }
}
